    // ---- long-message streaming -------------------------------------------

    #[test]
    fn sha256_streams_over_one_gibibyte() {
        // 1 GiB + 17 bytes exercises the 64-bit byte counter and implies
        // 2^33 bits, past the point where a 32-bit counter would wrap.
        const TOTAL: usize = (1 << 30) + 17;
        let chunk = [0x5au8; 64 * 1024];
        let mut h = Sha256::new();
        let mut left = TOTAL;
        while left > 0 {
            let n = core::cmp::min(left, chunk.len());
            h.update(&chunk[..n]);
            left -= n;
        }
        assert_hex(&h.finalize(), &GIB_SHA256, "sha256 1 GiB+17");
    }

    #[test]
    fn sha512_streams_over_one_gigabyte() {
        const TOTAL: usize = (1 << 30) + 129;
        let chunk = [0xa5u8; 64 * 1024];
        let mut h = Sha512::new();
        let mut left = TOTAL;
        while left > 0 {
            let n = core::cmp::min(left, chunk.len());
            h.update(&chunk[..n]);
            left -= n;
        }
        assert_hex(&h.finalize(), &GIB_SHA512, "sha512 1 GiB+129");
    }

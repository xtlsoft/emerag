    fn hex(bytes: &[u8]) -> String {
        let mut s = String::with_capacity(bytes.len() * 2);
        for b in bytes {
            s.push_str(&format!("{:02x}", b));
        }
        s
    }

    fn assert_hex(actual: &[u8], expected: &[u8], what: &str) {
        assert_eq!(hex(actual), hex(expected), "{}", what);
    }

    // ---- slow, independent reference implementations ----------------------
    //
    // These are deliberately written differently from the production code:
    // padding is built bit-by-bit into a vector and Ch/Maj/Sigma are evaluated
    // with explicit per-bit loops. They are far too slow for production but
    // make word packing and padding bugs visible, and they do not share code
    // with Core256/Core512.

    fn rotr32(x: u32, n: u32) -> u32 {
        let mut out = 0u32;
        let mut i = 0u32;
        while i < 32 {
            let bit = (x >> i) & 1;
            let dst = (i + 32 - n) % 32;
            out |= bit << dst;
            i += 1;
        }
        out
    }

    fn ch32(x: u32, y: u32, z: u32) -> u32 {
        let mut out = 0u32;
        let mut i = 0u32;
        while i < 32 {
            let b = ((x >> i) & 1) & ((y >> i) & 1) ^ (((x >> i) & 1) ^ 1) & ((z >> i) & 1);
            out |= b << i;
            i += 1;
        }
        out
    }

    fn maj32(x: u32, y: u32, z: u32) -> u32 {
        let mut out = 0u32;
        let mut i = 0u32;
        while i < 32 {
            let b = ((x >> i) & 1) & ((y >> i) & 1)
                ^ ((x >> i) & 1) & ((z >> i) & 1)
                ^ ((y >> i) & 1) & ((z >> i) & 1);
            out |= b << i;
            i += 1;
        }
        out
    }

    fn rotr64(x: u64, n: u32) -> u64 {
        let mut out = 0u64;
        let mut i = 0u32;
        while i < 64 {
            let bit = (x >> i) & 1;
            let dst = (i + 64 - n) % 64;
            out |= bit << dst;
            i += 1;
        }
        out
    }

    fn ch64(x: u64, y: u64, z: u64) -> u64 {
        let mut out = 0u64;
        let mut i = 0u32;
        while i < 64 {
            let b = ((x >> i) & 1) & ((y >> i) & 1) ^ (((x >> i) & 1) ^ 1) & ((z >> i) & 1);
            out |= b << i;
            i += 1;
        }
        out
    }

    fn maj64(x: u64, y: u64, z: u64) -> u64 {
        let mut out = 0u64;
        let mut i = 0u32;
        while i < 64 {
            let b = ((x >> i) & 1) & ((y >> i) & 1)
                ^ ((x >> i) & 1) & ((z >> i) & 1)
                ^ ((y >> i) & 1) & ((z >> i) & 1);
            out |= b << i;
            i += 1;
        }
        out
    }

    fn pad_bits(msg: &[u8], block_bits: usize, len_bits: usize) -> Vec<u8> {
        let mut bits = Vec::new();
        for &b in msg {
            let mut i = 8;
            while i > 0 {
                i -= 1;
                bits.push((b >> i) & 1);
            }
        }
        bits.push(1);
        while bits.len() % block_bits != block_bits - len_bits {
            bits.push(0);
        }
        let bitlen = (msg.len() as u128).wrapping_mul(8);
        let mut i = len_bits;
        while i > 0 {
            i -= 1;
            bits.push(((bitlen >> i) & 1) as u8);
        }
        bits
    }

    fn read_bits(bits: &[u8]) -> u64 {
        let mut v = 0u64;
        for &b in bits {
            v = (v << 1) | b as u64;
        }
        v
    }

    fn ref_sha256(msg: &[u8]) -> [u8; 32] {
        let bits = pad_bits(msg, 512, 64);
        let mut h = IV256;
        for block in bits.chunks(512) {
            let mut w = [0u32; 64];
            let mut i = 0;
            while i < 16 {
                w[i] = read_bits(&block[i * 32..(i + 1) * 32]) as u32;
                i += 1;
            }
            while i < 64 {
                let s0 = rotr32(w[i - 15], 7) ^ rotr32(w[i - 15], 18) ^ (w[i - 15] >> 3);
                let s1 = rotr32(w[i - 2], 17) ^ rotr32(w[i - 2], 19) ^ (w[i - 2] >> 10);
                w[i] = w[i - 16]
                    .wrapping_add(s0)
                    .wrapping_add(w[i - 7])
                    .wrapping_add(s1);
                i += 1;
            }
            let mut a = h[0];
            let mut b = h[1];
            let mut c = h[2];
            let mut d = h[3];
            let mut e = h[4];
            let mut f = h[5];
            let mut g = h[6];
            let mut hh = h[7];
            let mut i = 0;
            while i < 64 {
                let s1 = rotr32(e, 6) ^ rotr32(e, 11) ^ rotr32(e, 25);
                let t1 = hh
                    .wrapping_add(s1)
                    .wrapping_add(ch32(e, f, g))
                    .wrapping_add(K256[i])
                    .wrapping_add(w[i]);
                let s0 = rotr32(a, 2) ^ rotr32(a, 13) ^ rotr32(a, 22);
                let t2 = s0.wrapping_add(maj32(a, b, c));
                hh = g;
                g = f;
                f = e;
                e = d.wrapping_add(t1);
                d = c;
                c = b;
                b = a;
                a = t1.wrapping_add(t2);
                i += 1;
            }
            h[0] = h[0].wrapping_add(a);
            h[1] = h[1].wrapping_add(b);
            h[2] = h[2].wrapping_add(c);
            h[3] = h[3].wrapping_add(d);
            h[4] = h[4].wrapping_add(e);
            h[5] = h[5].wrapping_add(f);
            h[6] = h[6].wrapping_add(g);
            h[7] = h[7].wrapping_add(hh);
        }
        let mut out = [0u8; 32];
        let mut i = 0;
        while i < 8 {
            out[i * 4..i * 4 + 4].copy_from_slice(&h[i].to_be_bytes());
            i += 1;
        }
        out
    }

    fn ref_sha512_with(iv: [u64; 8], msg: &[u8]) -> [u8; 64] {
        let bits = pad_bits(msg, 1024, 128);
        let mut h = iv;
        for block in bits.chunks(1024) {
            let mut w = [0u64; 80];
            let mut i = 0;
            while i < 16 {
                w[i] = read_bits(&block[i * 64..(i + 1) * 64]);
                i += 1;
            }
            while i < 80 {
                let s0 = rotr64(w[i - 15], 1) ^ rotr64(w[i - 15], 8) ^ (w[i - 15] >> 7);
                let s1 = rotr64(w[i - 2], 19) ^ rotr64(w[i - 2], 61) ^ (w[i - 2] >> 6);
                w[i] = w[i - 16]
                    .wrapping_add(s0)
                    .wrapping_add(w[i - 7])
                    .wrapping_add(s1);
                i += 1;
            }
            let mut a = h[0];
            let mut b = h[1];
            let mut c = h[2];
            let mut d = h[3];
            let mut e = h[4];
            let mut f = h[5];
            let mut g = h[6];
            let mut hh = h[7];
            let mut i = 0;
            while i < 80 {
                let s1 = rotr64(e, 14) ^ rotr64(e, 18) ^ rotr64(e, 41);
                let t1 = hh
                    .wrapping_add(s1)
                    .wrapping_add(ch64(e, f, g))
                    .wrapping_add(K512[i])
                    .wrapping_add(w[i]);
                let s0 = rotr64(a, 28) ^ rotr64(a, 34) ^ rotr64(a, 39);
                let t2 = s0.wrapping_add(maj64(a, b, c));
                hh = g;
                g = f;
                f = e;
                e = d.wrapping_add(t1);
                d = c;
                c = b;
                b = a;
                a = t1.wrapping_add(t2);
                i += 1;
            }
            h[0] = h[0].wrapping_add(a);
            h[1] = h[1].wrapping_add(b);
            h[2] = h[2].wrapping_add(c);
            h[3] = h[3].wrapping_add(d);
            h[4] = h[4].wrapping_add(e);
            h[5] = h[5].wrapping_add(f);
            h[6] = h[6].wrapping_add(g);
            h[7] = h[7].wrapping_add(hh);
        }
        let mut out = [0u8; 64];
        let mut i = 0;
        while i < 8 {
            out[i * 8..i * 8 + 8].copy_from_slice(&h[i].to_be_bytes());
            i += 1;
        }
        out
    }

    fn ref_sha384(msg: &[u8]) -> [u8; 48] {
        let full = ref_sha512_with(IV384, msg);
        let mut out = [0u8; 48];
        out.copy_from_slice(&full[..48]);
        out
    }

    fn ref_sha512(msg: &[u8]) -> [u8; 64] {
        ref_sha512_with(IV512, msg)
    }

    fn pattern(n: usize) -> Vec<u8> {
        (0..n).map(|i| ((i * 37 + 11) & 0xff) as u8).collect()
    }


//! SHA-2 family (FIPS 180-4), HMAC (RFC 2104) and HKDF (RFC 5869).
//!
//! All hashes are streaming (new/update/finalize) with a one-shot digest
//! helper. State lives in fixed-size arrays, so update never allocates and
//! accepts input of any size; the byte counter is 64-bit for SHA-256 and
//! 128-bit for SHA-512/384, so messages larger than 1 GiB (and larger than
//! 4 GiB on 32-bit hosts) are hashed correctly.
//!
//! HMAC keys of any length are accepted: keys longer than the hash block size
//! are hashed first, shorter keys are zero-padded, exactly as RFC 2104 says.
//!
//! HKDF follows RFC 5869. hkdf_expand_* enforces the RFC limit of 255 output
//! blocks and returns Err when the requested length exceeds it.


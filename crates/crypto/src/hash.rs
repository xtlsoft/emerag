// ---------------------------------------------------------------------------
// HKDF (RFC 5869)
// ---------------------------------------------------------------------------

fn expand_sha256(prk: &[u8], info: &[u8], out: &mut [u8]) {
    let mut t = [0u8; 32];
    let mut tlen = 0usize;
    let mut counter = 1u8;
    for chunk in out.chunks_mut(32) {
        let mut mac = Hmac256::new(prk);
        mac.update(&t[..tlen]);
        mac.update(info);
        mac.update(&[counter]);
        let block = mac.finalize();
        t = block;
        tlen = 32;
        chunk.copy_from_slice(&block[..chunk.len()]);
        counter = counter.wrapping_add(1);
    }
    crate::ct::wipe(&mut t);
}

fn expand_sha384(prk: &[u8], info: &[u8], out: &mut [u8]) {
    let mut t = [0u8; 48];
    let mut tlen = 0usize;
    let mut counter = 1u8;
    for chunk in out.chunks_mut(48) {
        let mut mac = Hmac384::new(prk);
        mac.update(&t[..tlen]);
        mac.update(info);
        mac.update(&[counter]);
        let block = mac.finalize();
        t = block;
        tlen = 48;
        chunk.copy_from_slice(&block[..chunk.len()]);
        counter = counter.wrapping_add(1);
    }
    crate::ct::wipe(&mut t);
}

/// HKDF-Extract with SHA-256. An empty salt is equivalent to a zero salt
/// because HMAC already zero-pads keys.
pub fn hkdf_extract_sha256(salt: &[u8], ikm: &[u8]) -> [u8; 32] {
    hmac_sha256(salt, ikm)
}

/// HKDF-Extract with SHA-384.
pub fn hkdf_extract_sha384(salt: &[u8], ikm: &[u8]) -> [u8; 48] {
    hmac_sha384(salt, ikm)
}

/// HKDF-Expand with SHA-256. Output length must be at most 255*32 bytes.
pub fn hkdf_expand_sha256(prk: &[u8; 32], info: &[u8], out: &mut [u8]) -> Result<()> {
    if out.len() > 255 * 32 {
        return Err(Error::new(
            "hkdf-expand-sha256: output longer than 255*32 bytes",
        ));
    }
    expand_sha256(prk, info, out);
    Ok(())
}

/// HKDF-Expand with SHA-384. Output length must be at most 255*48 bytes.
pub fn hkdf_expand_sha384(prk: &[u8], info: &[u8], out: &mut [u8]) -> Result<()> {
    if out.len() > 255 * 48 {
        return Err(Error::new(
            "hkdf-expand-sha384: output longer than 255*48 bytes",
        ));
    }
    expand_sha384(prk, info, out);
    Ok(())
}

/// One-shot HKDF-SHA256 (extract then expand).
pub fn hkdf_sha256(salt: &[u8], ikm: &[u8], info: &[u8], out: &mut [u8]) -> Result<()> {
    if out.len() > 255 * 32 {
        return Err(Error::new("hkdf-sha256: output longer than 255*32 bytes"));
    }
    let mut prk = hkdf_extract_sha256(salt, ikm);
    expand_sha256(&prk, info, out);
    crate::ct::wipe(&mut prk);
    Ok(())
}


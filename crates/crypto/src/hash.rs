#[derive(Clone)]
struct Core512 {
    h: [u64; 8],
    buf: [u8; 128],
    buflen: usize,
    total: u128,
}

impl Core512 {
    fn new(iv: [u64; 8]) -> Self {
        Core512 {
            h: iv,
            buf: [0u8; 128],
            buflen: 0,
            total: 0,
        }
    }

    fn compress(&mut self, block: &[u8]) {
        debug_assert!(block.len() >= 128);
        let mut w = [0u64; 80];
        let mut i = 0;
        while i < 16 {
            let j = i * 8;
            let mut word = [0u8; 8];
            word.copy_from_slice(&block[j..j + 8]);
            w[i] = u64::from_be_bytes(word);
            i += 1;
        }
        while i < 80 {
            let x = w[i - 15];
            let y = w[i - 2];
            let s0 = x.rotate_right(1) ^ x.rotate_right(8) ^ (x >> 7);
            let s1 = y.rotate_right(19) ^ y.rotate_right(61) ^ (y >> 6);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
            i += 1;
        }

        let mut a = self.h[0];
        let mut b = self.h[1];
        let mut c = self.h[2];
        let mut d = self.h[3];
        let mut e = self.h[4];
        let mut f = self.h[5];
        let mut g = self.h[6];
        let mut h = self.h[7];

        let mut i = 0;
        while i < 80 {
            let s1 = e.rotate_right(14) ^ e.rotate_right(18) ^ e.rotate_right(41);
            let ch = (e & f) ^ ((!e) & g);
            let t1 = h
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K512[i])
                .wrapping_add(w[i]);
            let s0 = a.rotate_right(28) ^ a.rotate_right(34) ^ a.rotate_right(39);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);

            h = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
            i += 1;
        }

        self.h[0] = self.h[0].wrapping_add(a);
        self.h[1] = self.h[1].wrapping_add(b);
        self.h[2] = self.h[2].wrapping_add(c);
        self.h[3] = self.h[3].wrapping_add(d);
        self.h[4] = self.h[4].wrapping_add(e);
        self.h[5] = self.h[5].wrapping_add(f);
        self.h[6] = self.h[6].wrapping_add(g);
        self.h[7] = self.h[7].wrapping_add(h);
    }

    fn update(&mut self, mut data: &[u8]) {
        self.total = self.total.wrapping_add(data.len() as u128);

        if self.buflen != 0 {
            let take = core::cmp::min(128 - self.buflen, data.len());
            self.buf[self.buflen..self.buflen + take].copy_from_slice(&data[..take]);
            self.buflen += take;
            data = &data[take..];
            if self.buflen == 128 {
                let block = self.buf;
                self.compress(&block);
                self.buflen = 0;
            }
        }

        let mut chunks = data.chunks_exact(128);
        for block in &mut chunks {
            self.compress(block);
        }
        let rest = chunks.remainder();
        if !rest.is_empty() {
            self.buf[..rest.len()].copy_from_slice(rest);
            self.buflen = rest.len();
        }
    }

    fn finalize(mut self) -> [u8; 64] {
        let bits = self.total.wrapping_mul(8);

        self.buf[self.buflen] = 0x80;
        self.buflen += 1;
        if self.buflen > 112 {
            for b in self.buf[self.buflen..].iter_mut() {
                *b = 0;
            }
            let block = self.buf;
            self.compress(&block);
            self.buflen = 0;
        }
        for b in self.buf[self.buflen..112].iter_mut() {
            *b = 0;
        }
        self.buf[112..128].copy_from_slice(&bits.to_be_bytes());
        let block = self.buf;
        self.compress(&block);

        let mut out = [0u8; 64];
        let mut i = 0;
        while i < 8 {
            out[i * 8..i * 8 + 8].copy_from_slice(&self.h[i].to_be_bytes());
            i += 1;
        }
        out
    }
}

